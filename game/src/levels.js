// Parse one ASCII map into world objects (pixel coordinates, tile centres).
export function parseLevel(idx) {
  const raw = RAW[idx];
  const walls = [];
  const covers = [];
  const scrolls = [];
  let key = null;
  let door = null;
  let exit = null;
  let player = { x: 60, y: 60 };
  const guardSpawns = [];
  raw.map.forEach((row, ry) => {
    for (let rx = 0; rx < row.length; rx++) {
      const ch = row[rx];
      const cx = rx * TILE + TILE / 2;
      const cy = ry * TILE + TILE / 2;
      const rect = { x: rx * TILE, y: ry * TILE, w: TILE, h: TILE };
      if (ch === '#') walls.push(rect);
      else if (ch === 'C') covers.push({ ...rect, kind: 'crate' });
      else if (ch === 'B') covers.push({ ...rect, kind: 'bush' });
      else if (ch === 'T') covers.push({ ...rect, kind: 'table' });
      else if (ch === 'P') covers.push({ ...rect, kind: 'pillar' });
      else if (ch === 'K') key = { x: cx, y: cy, taken: false };
      else if (ch === 'D') door = { ...rect, x: cx, y: cy, open: false };
      else if (ch === 'S') scrolls.push({ x: cx, y: cy, taken: false });
      else if (ch === 'E') exit = { x: cx, y: cy };
      else if (ch === '@') player = { x: cx, y: cy };
      else if (ch === 'G') guardSpawns.push({ x: cx, y: cy });
    }
  });
  return {
    index: idx,
    name: raw.name,
    sub: raw.sub,
    theme: raw.theme,
    pebbles: raw.pebbles,
    walls,
    covers,
    scrolls,
    key,
    door,
    exit,
    player,
    guardDefs: raw.guards,
    guardSpawns,
    cols: COLS,
    rows: ROWS,
    rawMap: raw.map,
  };
}

export const LEVELS = RAW.map((r, i) => ({ name: r.name, sub: r.sub, pebbles: r.pebbles, guards: r.guards.length }));
